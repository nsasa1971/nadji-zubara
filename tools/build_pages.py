HOURS_LABELS = {'mon': 'Ponedeljak', 'tue': 'Utorak', 'wed': 'Sreda', 'thu': 'Četvrtak', 'fri': 'Petak', 'sat': 'Subota', 'sun': 'Nedelja'}


def norm_phone(p):
    """Isto kao PF.normalizePhone u js/profile-common.js: +381 XX XXXXXXX ili ''."""
    if not isinstance(p, str) or len(p) > 30:
        return ''
    d = re.sub(r'[^0-9+]', '', p)
    if d.startswith('00381'):
        d = '+' + d[2:]
    elif d.startswith('381'):
        d = '+' + d
    elif d.startswith('0'):
        d = '+381' + d[1:]
    if not re.fullmatch(r'\+381[0-9]{8,10}', d):
        return ''
    rest = d[4:]
    return '+381 ' + rest[:2] + ' ' + rest[2:]


def safe_http_url(u):
    if not isinstance(u, str) or len(u) > 300:
        return ''
    u = u.strip()
    return u if re.fullmatch(r'https?://[^\s<>"\']+', u) else ''


def _txt(v, lo, hi):
    if not isinstance(v, str):
        return ''
    t = CTRL_RE.sub(' ', v).strip()
    t = re.sub(r'[ \t]+', ' ', t)
    return t if lo <= len(t) <= hi else ''


def translit(t):
    """Ćirilica -> latinica, uz očuvanje velikih slova (slug i naziv grada; prikazani naziv ordinacije ostaje original)."""
    out = []
    for ch in t:
        m = CYR.get(ch.lower())
        out.append((m.capitalize() if ch.isupper() else m) if m else ch)
    return ''.join(out)


def load_new_clinics(imported, service_keys, warn=print):
    """Vraća listu ordinacija (kao load_clinics) iz data/new-clinics.json; prazna lista ako snimka nema."""
    if not NEW_SRC.exists():
        return []
    try:
        rows = json.loads(NEW_SRC.read_text(encoding='utf-8'))
    except ValueError as e:
        warn(f'UPOZORENJE: {NEW_SRC.name} nije ispravan JSON ({e}); nove ordinacije se preskaču')
        return []
    if not isinstance(rows, list):
        warn(f'UPOZORENJE: {NEW_SRC.name} nije lista; nove ordinacije se preskaču')
        return []
    city_by_slug = {}
    for c in imported:
        if c['city'] not in SKIP_CITIES:
            city_by_slug.setdefault(slugify(c['city']), c['city'])
    used = defaultdict(set)   # slug grada -> zauzeti slugovi ordinacija
    for c in imported:
        cs = slugify(c['city'])
        used[cs].add(clinic_slug(c, cs))
    out, seen_ids = [], set()
    for r in sorted((x for x in rows if isinstance(x, dict)), key=lambda x: str(x.get('clinic_id'))):
        cid = r.get('clinic_id')
        if not isinstance(cid, str) or not NEW_ID_RE.match(cid) or cid in seen_ids:
            warn(f'UPOZORENJE: nova ordinacija preskočena (neispravan ili dupli id): {str(cid)[:60]}')
            continue
        if r.get('status') != 'published':
            warn(f'UPOZORENJE: {cid} preskočena (status nije published)')
            continue
        name, city, address = _txt(r.get('naziv'), 2, 150), _txt(r.get('grad'), 2, 80), _txt(r.get('adresa'), 3, 200)
        if not (name and city and address) or city in SKIP_CITIES:
            warn(f'UPOZORENJE: {cid} preskočena (naziv, grad ili adresa nisu ispravni)')
            continue
        city = translit(city)   # grad u latinici (stranice gradova su latinične)
        cslug = slugify(city)
        if not cslug or cslug in RESERVED:
            warn(f'UPOZORENJE: {cid} preskočena (slug grada "{cslug}" je prazan ili rezervisan)')
            continue
        city = city_by_slug.setdefault(cslug, city)   # "novi sad" -> "Novi Sad" (isti slug = isti grad)
        base = slugify(translit(name)) or 'ordinacija'
        slug = base
        if slug in used[cslug] or slug.isdigit():
            slug = f'{base}-{cid[-4:]}'
        if slug in used[cslug] or slug.isdigit():
            warn(f'UPOZORENJE: {cid} preskočena (sudar slugova u gradu {city}: "{slug}")')
            continue
        used[cslug].add(slug)
        seen_ids.add(cid)
        phone = norm_phone(_txt(r.get('telefon'), 6, 40))
        services = [k for k in (r.get('services') if isinstance(r.get('services'), list) else []) if k in service_keys]
        custom = [_txt(x, 1, 60) for x in (r.get('custom_services') if isinstance(r.get('custom_services'), list) else [])][:10]
        hours = {}
        if isinstance(r.get('hours'), dict):
            for k in HOURS_KEYS:
                t = _txt(r['hours'].get(k), 1, 60)
                if t:
                    hours[k] = t
        out.append({'id': cid, 'name': name, 'city': city, 'address': address,
                    'phone': phone if valid_phone(phone) else '', 'phone_raw': phone,
                    'new': True, 'slug': slug,
                    'description': _txt(r.get('description'), 1, 600),
                    'hours_text': '' if hours else _txt(r.get('hours_text'), 1, 200),
                    'hours': hours,
                    'services': services, 'custom_services': [x for x in custom if x],
                    'website': safe_http_url(r.get('website')),
                    'socials_text': _txt(r.get('socials_text'), 1, 200)})
    return out


def opstina_of(c):
    """Opština iz adrese ('..., Beograd - Vračar' -> 'Vračar') ili None."""
    if c['city'] != OPSTINE_CITY:
        return None
    m = OPSTINA_RE.search(c['address'])
    if not m:
        return None
    label = m.group(1).strip()
    if OPSTINE_MERGE_COMPOUND:
        label = label.split(' - ')[0].strip()
    return label or None


CYR = dict(zip('абвгдђежзијклљмнњопрстћуфхцчџш', ['a','b','v','g','d','đ','e','ž','z','i','j','k','l','lj','m','n','nj','o','p','r','s','t','ć','u','f','h','c','č','dž','š']))

# Uvodne opšte reči u nazivu (samo za redosled; prikaz naziva se ne menja).
SORT_STRIP_PHRASES = [
    "specijalisticka stomatoloska ordinacija", "stomatoloska specijalisticka ordinacija",
    "samostalna stomatoloska ordinacija", "opsta stomatoloska ordinacija",
    "privatna stomatoloska ordinacija", "stomatoloska privatna ordinacija",
    "specijalisticka ordinacija dentalne medicine", "opsta ordinacija dentalne medicine",
    "ordinacija opste stomatologije", "ordinacija dentalne medicine",
    "specijalisticka ordinacija", "opsta ordinacija", "stomatoloska ordinacija",
    "zubna ordinacija", "ordinacija",
    # titule na početku (posle opštih reči): "Dr", "Dr.", "Prim. dr"
    "prim dr", "dr",
]
_PHRASES = sorted((tuple(p.split()) for p in SORT_STRIP_PHRASES), key=len, reverse=True)
# Redosled slova srpske latinice; q, w, x, y su na svojim mestima u abecedi; cifre idu pre slova
_ALPHA = "abcčćdđefghijklmnopqrsštuvwxyzž"
_ORDER = {ch: i + 10 for i, ch in enumerate(_ALPHA)}


def _latin(text):
    return ''.join(CYR.get(ch, ch) for ch in text.lower())


def sort_key(name):
    """Ključ za redosled po nazivu bez uvodnih opštih reči ("Stomatološka ordinacija ...")."""
    words = _latin(name).split()
    plain = [slugify(w) for w in words]  # bez dijakritika, samo za poređenje fraza
    i = 0
    while i < len(words):
        for ph in _PHRASES:
            if tuple(plain[i:i + len(ph)]) == ph:
                i += len(ph)
                break
        else:
            break
    rest = ' '.join(words[i:]) if i < len(words) else ' '.join(words)
    return [(_ORDER.get(ch, 0 if ch == ' ' else 1 if ch.isdigit() else 5), ch) for ch in rest]


def display_address(c, city, opstina_label=None):
    """Adresa za karticu. Na stranicama Beograda i opština se ne ponavlja grad (i opština):
    'Gramšijeva 1a, Beograd - Novi Beograd' -> 'Gramšijeva 1a, Novi Beograd' (stranica grada),
    -> 'Gramšijeva 1a' (stranica te opštine). Ostali gradovi: adresa ostaje kakva jeste."""
    addr = c['address']
    if city != OPSTINE_CITY:
        return addr
    m = re.search(r',\s*' + re.escape(OPSTINE_CITY) + r'\s*-\s*(.+?)\s*$', addr)
    if not m:
        return addr
    street, rest = addr[:m.start()], m.group(1)
    if opstina_label is None:
        return f'{street}, {rest}'
    parts = [x.strip() for x in rest.split(' - ')]
    tail = ' - '.join(parts[1:]) if slugify(parts[0]) == slugify(opstina_label) else rest
    return f'{street}, {tail}' if tail else street


def clinic_slug(c, city_slug):
    """id je 'imp-<naziv>-<grad>[-N]' -> '<naziv>[-N]' (jedinstven unutar grada)."""
    if c.get('slug'):   # nove ordinacije: slug je dodeljen pri učitavanju (load_new_clinics)
        return c['slug']
    s = c['id']
    if s.startswith('imp-'):
        s = s[4:]
    m = re.match(r'^(.*)-' + re.escape(city_slug) + r'(-\d+)?$', s)
    if m:
        s = m.group(1) + (m.group(2) or '')
    return s


