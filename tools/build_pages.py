# -*- coding: utf-8 -*-
"""
Generiše statične SEO stranice iz js/imported-clinics.js (fajl se samo čita).

  /<grad>/index.html                 stranica grada (lista ordinacija); gradovi sa više od
                                     PAGE_SIZE ordinacija dele se: /<grad>/, /<grad>/2/, ...
  /<grad>/<ordinacija>/index.html    jedna stranica po ordinaciji
  /sitemap.xml, /robots.txt

Svaka stranica ima svoj <title>, meta opis i canonical link, a osnovni sadržaj
(naziv, adresa, telefon, link "Prijavi netačan podatak") je u HTML-u, vidljiv bez
JavaScript-a. Koordinate (lat/lng) se NE koriste. Zaglavlje, podnožje i css/style.css
su isti kao na ostalim stranicama (zaglavlje i podnožje se čitaju iz index.html).

Pokretanje:
    python tools/build_pages.py                 # generiše sve u koren repoa
    python tools/build_pages.py --sample DIR    # samo jedan grad (2 strane) + jedna ordinacija u DIR
                                                # (probni prikaz; ne dira repo, bez sitemap/robots)

Sve apsolutne adrese (canonical, sitemap, og:url, JSON-LD) grade se iz BASE_URL.
"""
import argparse
import datetime
import html
import json
import re
import shutil
import sys
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path
from urllib.parse import quote

# ---------------------------------------------------------------------------
# Jedino mesto gde se definiše adresa sajta.
BASE_URL = "https://nadjizubara.netlify.app"
# ---------------------------------------------------------------------------

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "js" / "imported-clinics.js"
SITE_NAME = "Nađi Zubara"
MARKER = "<!-- generated by tools/build_pages.py -->"
PAGE_SIZE = 200  # gradovi sa više ordinacija dele se na stranice po PAGE_SIZE
# Koreni koji već postoje u repou i ne smeju biti prepisani gradom.
RESERVED = {"css", "img", "js", "tools", "index", "pretraga", "kontakt", "cenovnik",
            "ordinacija", "prijava", "nalog", "dodaj-ordinaciju"}
SKIP_CITIES = {"", "Nepoznato"}

SERBIAN_MAP = str.maketrans({'č': 'c', 'ć': 'c', 'ž': 'z', 'š': 's', 'đ': 'dj',
                             'Č': 'C', 'Ć': 'C', 'Ž': 'Z', 'Š': 'S', 'Đ': 'Dj'})

SCRIPTS = """<script src="/js/icons.js"></script>
<script src="/js/auth.js"></script>
<script src="/js/header-auth.js"></script>
<script src="/js/main.js"></script>"""


def slugify(text):
    text = text.translate(SERBIAN_MAP)
    text = unicodedata.normalize('NFKD', text).encode('ascii', 'ignore').decode('ascii')
    return re.sub(r'[^a-zA-Z0-9]+', '-', text).strip('-').lower()


def esc(s):
    return html.escape(s, quote=True)


def url(path):
    return BASE_URL.rstrip('/') + path


def clip(text, n=158):
    text = re.sub(r'\s+', ' ', text).strip()
    return text if len(text) <= n else text[:n - 1].rstrip(' ,.;') + '…'


# ---------------------------------------------------------------------------
# Učitavanje podataka (samo čitanje, bez Node-a): prvi stringovi u svakom redu su JSON
# (generator koristi json.dumps). Čitaju se samo id, naziv, grad, adresa i telefon.
STR = r'("(?:[^"\\]|\\.)*")'
ROW = re.compile(
    r'^\{id:' + STR + r',name:' + STR + r',city:' + STR + r',address:' + STR + r',phone:' + STR + r',',
    re.M)


def load_clinics():
    text = SRC.read_text(encoding='utf-8')
    out = []
    for m in ROW.finditer(text):
        cid, name, city, address, phone = (json.loads(g) for g in m.groups())
        out.append({'id': cid, 'name': name.strip(), 'city': city.strip(),
                    'address': address.strip(), 'phone': phone.strip()})
    if not out:
        sys.exit('Nije pronađena nijedna ordinacija u ' + str(SRC))
    return out


def clinic_slug(c, city_slug):
    """id je 'imp-<naziv>-<grad>[-N]' -> '<naziv>[-N]' (jedinstven unutar grada)."""
    s = c['id']
    if s.startswith('imp-'):
        s = s[4:]
    m = re.match(r'^(.*)-' + re.escape(city_slug) + r'(-\d+)?$', s)
    if m:
        s = m.group(1) + (m.group(2) or '')
    return s


# ---------------------------------------------------------------------------
_CHROME = None


def chrome():
    """Zaglavlje i podnožje iz index.html (isto kao na ostalim stranicama); relativne
    putanje se prevode u putanje od korena sajta."""
    global _CHROME
    if _CHROME is None:
        src = (ROOT / 'index.html').read_text(encoding='utf-8')
        head = re.search(r'<header class="site-header">.*?</header>', src, re.S).group(0)
        foot = re.search(r'<footer class="site-footer">.*?</footer>', src, re.S).group(0)
        rel = re.compile(r'\b(href|src)="(?!https?:|//|#|/|mailto:|tel:|data:)([^"]+)"')
        head = rel.sub(lambda m: f'{m.group(1)}="/{m.group(2)}"', head).replace(' class="active"', '')
        foot = rel.sub(lambda m: f'{m.group(1)}="/{m.group(2)}"', foot)
        foot = foot.replace('<span data-year></span>', str(datetime.date.today().year))
        _CHROME = (head, foot)
    return _CHROME


def page(title, description, canonical_path, body, jsonld=None, prev_path=None, next_path=None):
    canonical = url(canonical_path)
    ld = ''
    if jsonld:
        ld = ('\n<script type="application/ld+json">'
              + json.dumps(jsonld, ensure_ascii=False).replace('</', '<\\/') + '</script>')
    rel = ''
    if prev_path:
        rel += f'\n<link rel="prev" href="{esc(url(prev_path))}">'
    if next_path:
        rel += f'\n<link rel="next" href="{esc(url(next_path))}">'
    head, foot = chrome()
    return f'''<!DOCTYPE html>
{MARKER}
<html lang="sr">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{esc(title)}</title>
<meta name="description" content="{esc(description)}">
<link rel="canonical" href="{esc(canonical)}">{rel}
<meta name="robots" content="index, follow">
<meta property="og:type" content="website">
<meta property="og:site_name" content="{SITE_NAME}">
<meta property="og:title" content="{esc(title)}">
<meta property="og:description" content="{esc(description)}">
<meta property="og:url" content="{esc(canonical)}">
<link rel="icon" href="/img/logo.webp">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Poppins:wght@400;500;600;700;800&display=swap" rel="stylesheet">
<link rel="stylesheet" href="/css/style.css">{ld}
</head>
<body>
{head}

<main class="section-tight">
<div class="container">
{body}
</div>
</main>

{foot}
{SCRIPTS}
</body>
</html>
'''


def report_href(c):
    return ('/kontakt.html?subject=netacan-podatak&clinic=' + quote(c['name']) +
            '&city=' + quote(c['city']) + '&id=' + quote(c['id']))


def clinic_page(c, city_slug, slug, same_name=False):
    path = f'/{city_slug}/{slug}/'
    # ordinacije sa istim nazivom u istom gradu dobijaju adresu u naslovu (jedinstveni naslovi)
    label = f"{c['name']}, {c['address']}" if same_name else c['name']
    title = f"{label} – {c['city']} | {SITE_NAME}"
    desc = f"{c['name']}, {c['address']}."
    if c['phone']:
        desc += f" Telefon: {c['phone']}."
    desc += f" Adresa i kontakt ordinacije, grad: {c['city']}."
    if c['phone']:
        tel = re.sub(r'[^+0-9]', '', c['phone'])
        phone_html = f'<p><strong>Telefon:</strong> <a href="tel:{esc(tel)}">{esc(c["phone"])}</a></p>'
    else:
        phone_html = '<p><strong>Telefon:</strong> nije dostupan</p>'
    body = f'''<div class="breadcrumbs"><a href="/index.html">Početna</a> / <a href="/{city_slug}/">{esc(c['city'])}</a> / {esc(c['name'])}</div>
<article class="info-card">
  <h1>{esc(c['name'])}</h1>
  <p><strong>Adresa:</strong> {esc(c['address'])}</p>
  {phone_html}
  <p><strong>Grad:</strong> <a href="/{city_slug}/">{esc(c['city'])}</a></p>
  <p><a href="/{city_slug}/">Sve ordinacije u gradu {esc(c['city'])}</a></p>
  <p>Radno vreme, usluge i ocene za ovu ordinaciju još nisu dostupni.</p>
  <p>
    <a class="btn btn-primary" href="/ordinacija.html?id={esc(c['id'])}">Otvori u pretrazi</a>
  </p>
  <p style="font-size:14px;"><a href="{esc(report_href(c))}">Prijavi netačan podatak</a></p>
</article>'''
    ld = {"@context": "https://schema.org", "@type": "Dentist", "name": c['name'],
          "url": url(path), "address": c['address']}
    if c['phone']:
        ld["telephone"] = c['phone']
    return path, page(title, clip(desc), path, body, ld)


def city_page_path(slug, k):
    return f'/{slug}/' if k == 1 else f'/{slug}/{k}/'


def city_pages(city, slug, clinics_with_slug):
    """Lista (path, html): jedna stranica grada, ili više po PAGE_SIZE ordinacija."""
    n = len(clinics_with_slug)
    ordered = sorted(clinics_with_slug, key=lambda x: x[0]['name'].lower())
    pages = [ordered[i:i + PAGE_SIZE] for i in range(0, n, PAGE_SIZE)] or [[]]
    total = len(pages)
    search = f'/pretraga.html?city={quote(city)}'
    out = []
    for k, chunk in enumerate(pages, start=1):
        path = city_page_path(slug, k)
        suffix = f' – strana {k}' if total > 1 else ''
        title = f"Zubari i stomatološke ordinacije {city} ({n}){suffix} | {SITE_NAME}"
        desc = clip(f"Zubari i stomatološke ordinacije, grad: {city}. Spisak ordinacija ({n}) sa adresama i telefonima"
                    + (f", strana {k} od {total}" if total > 1 else '') + f". Pronađite zubara preko {SITE_NAME}.")
        items = '\n'.join(
            f'  <li><a href="/{slug}/{cs}/">{esc(c["name"])}</a> '
            f'<span style="color:var(--muted);">— {esc(c["address"])}</span></li>'
            for c, cs in chunk)
        prev_path = city_page_path(slug, k - 1) if k > 1 else None
        next_path = city_page_path(slug, k + 1) if k < total else None
        pager = ''
        if total > 1:
            links = []
            if prev_path:
                links.append(f'<a rel="prev" href="{prev_path}">&larr; Prethodna</a>')
            links.append(f'<span>Strana {k} od {total}</span>')
            if next_path:
                links.append(f'<a rel="next" href="{next_path}">Sledeća &rarr;</a>')
            pager = ('<nav class="city-pager" aria-label="Strane" '
                     'style="display:flex;gap:18px;align-items:center;margin:18px 0;">'
                     + ' '.join(links) + '</nav>')
        h1 = f'Zubari i stomatološke ordinacije – {esc(city)}' + (f' (strana {k})' if total > 1 else '')
        crumbs = ('<a href="/index.html">Početna</a> / ' +
                  (f'<a href="/{slug}/">{esc(city)}</a> / Strana {k}' if k > 1 else esc(city)))
        body = f'''<div class="breadcrumbs">{crumbs}</div>
<h1>{h1}</h1>
<p>Grad: {esc(city)}. Pregled stomatoloških ordinacija ({n}).
<a href="{esc(search)}">Pretraži ordinacije u gradu {esc(city)}</a> po usluzi i uz filtere.</p>
{pager}
<ul class="clinic-link-list">
{items}
</ul>
{pager}'''
        out.append((path, page(title, desc, path, body, prev_path=prev_path, next_path=next_path)))
    return out


def sitemap(paths):
    urls = '\n'.join(f'  <url><loc>{html.escape(url(p))}</loc></url>' for p in paths)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + '\n</urlset>\n')


def robots():
    # Namerno bez Disallow za prijava/nalog/dodaj-ordinaciju: te stranice nose noindex
    # i preusmerenje, a robots.txt zabrana bi sprečila crawler da vidi noindex.
    return f"User-agent: *\nAllow: /\n\nSitemap: {url('/sitemap.xml')}\n"


def write(base, rel_path, content):
    target = base / rel_path.strip('/') / 'index.html'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding='utf-8')


def clean_previous(base):
    """Briše samo ranije generisane direktorijume (prepoznaju se po MARKER-u)."""
    removed = 0
    for d in base.iterdir():
        idx = d / 'index.html'
        if d.is_dir() and idx.exists() and d.name not in RESERVED and not d.name.startswith('.'):
            if MARKER in idx.read_text(encoding='utf-8', errors='ignore')[:200]:
                shutil.rmtree(d)
                removed += 1
    return removed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sample', metavar='DIR', help='generiši samo jedan grad i jednu ordinaciju u DIR')
    args = ap.parse_args()

    clinics = load_clinics()
    by_city = defaultdict(list)
    skipped = 0
    for c in clinics:
        if c['city'] in SKIP_CITIES:
            skipped += 1
            continue
        by_city[c['city']].append(c)

    same_name_counts = Counter((c['name'].lower(), c['city']) for c in clinics)

    # slugovi gradova + provere sudara
    city_slugs = {}
    for city in by_city:
        s = slugify(city)
        if not s or s in RESERVED:
            sys.exit(f'Slug grada "{city}" -> "{s}" je prazan ili rezervisan')
        if s in city_slugs.values():
            sys.exit(f'Dva grada daju isti slug: {s}')
        city_slugs[city] = s

    plan = {}  # grad -> [(clinic, slug)]
    for city, lst in by_city.items():
        seen = set()
        plan[city] = []
        total_pages = -(-len(lst) // PAGE_SIZE)
        page_numbers = {str(k) for k in range(2, total_pages + 1)}  # /<grad>/<broj strane>/
        for c in lst:
            cs = clinic_slug(c, city_slugs[city])
            if not cs or cs in seen or cs in page_numbers:
                sys.exit(f'Sudar ili neispravan slug ordinacije u {city}: "{cs}" ({c["id"]})')
            seen.add(cs)
            plan[city].append((c, cs))

    if args.sample:
        out = Path(args.sample)
        out.mkdir(parents=True, exist_ok=True)
        city = 'Beograd' if 'Beograd' in plan else next(iter(plan))
        for pth, html_ in city_pages(city, city_slugs[city], plan[city])[:2]:
            write(out, pth, html_)
        c, cs = plan[city][0]
        pth, html_ = clinic_page(c, city_slugs[city], cs, same_name_counts[(c['name'].lower(), city)] > 1)
        write(out, pth, html_)
        print('Uzorak upisan u', out)
        return

    removed = clean_previous(ROOT)
    paths = ['/', '/pretraga.html', '/kontakt.html']
    n_clinic = n_city_pages = 0
    for city in sorted(plan, key=lambda x: city_slugs[x]):
        slug = city_slugs[city]
        for pth, html_ in city_pages(city, slug, plan[city]):
            write(ROOT, pth, html_)
            paths.append(pth)
            n_city_pages += 1
        for c, cs in plan[city]:
            pth, html_ = clinic_page(c, slug, cs, same_name_counts[(c['name'].lower(), city)] > 1)
            write(ROOT, pth, html_)
            paths.append(pth)
            n_clinic += 1
    (ROOT / 'sitemap.xml').write_text(sitemap(paths), encoding='utf-8')
    (ROOT / 'robots.txt').write_text(robots(), encoding='utf-8')
    print(f'Gradova: {len(plan)}, stranica gradova: {n_city_pages}, ordinacija: {n_clinic}, '
          f'preskočeno (nepoznat grad): {skipped}, obrisano starih direktorijuma: {removed}, '
          f'URL-ova u sitemap-u: {len(paths)}')


if __name__ == '__main__':
    main()
