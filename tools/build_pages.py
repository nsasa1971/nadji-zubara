# -*- coding: utf-8 -*-
"""
Generiše statične SEO stranice iz js/imported-clinics.js (fajl se samo čita).

  /<grad>/index.html              jedna stranica po gradu (lista ordinacija)
  /<grad>/<ordinacija>/index.html jedna stranica po ordinaciji
  /sitemap.xml, /robots.txt

Svaka stranica ima svoj <title>, meta opis i canonical link, a osnovni sadržaj
(naziv, adresa, telefon, link "Prijavi netačan podatak") je u HTML-u, vidljiv bez
JavaScript-a. Koordinate (lat/lng) se NE koriste.

Pokretanje:
    python tools/build_pages.py                 # generiše sve u koren repoa
    python tools/build_pages.py --sample DIR    # samo jedan grad + jedna ordinacija u DIR
                                                # (probni prikaz; ne dira repo, bez sitemap/robots)

Sve apsolutne adrese (canonical, sitemap, og:url, JSON-LD) grade se iz BASE_URL.
"""
import argparse
import html
import json
import re
import shutil
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

# ---------------------------------------------------------------------------
# Jedino mesto gde se definiše adresa sajta.
BASE_URL = "https://nadjizubara.netlify.app"
# ---------------------------------------------------------------------------

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "js" / "imported-clinics.js"
SITE_NAME = "Nađi Zubara"
MARKER = "<!-- generated by tools/build_pages.py -->"
# Koreni koji već postoje u repou i ne smeju biti prepisani gradom.
RESERVED = {"css", "img", "js", "tools", "index", "pretraga", "kontakt", "cenovnik",
            "ordinacija", "prijava", "nalog", "dodaj-ordinaciju"}
SKIP_CITIES = {"", "Nepoznato"}

SERBIAN_MAP = str.maketrans({'č': 'c', 'ć': 'c', 'ž': 'z', 'š': 's', 'đ': 'dj',
                             'Č': 'C', 'Ć': 'C', 'Ž': 'Z', 'Š': 'S', 'Đ': 'Dj'})


def slugify(text):
    text = text.translate(SERBIAN_MAP)
    text = unicodedata.normalize('NFKD', text).encode('ascii', 'ignore').decode('ascii')
    return re.sub(r'[^a-zA-Z0-9]+', '-', text).strip('-').lower()


def esc(s):
    return html.escape(s, quote=True)


# ---------------------------------------------------------------------------
# Učitavanje podataka (samo čitanje, bez Node-a): svaki red je JS objekat čiji su
# prvi stringovi napisani kao JSON (generator koristi json.dumps).
STR = r'("(?:[^"\\]|\\.)*")'
ROW = re.compile(
    r'^\{id:' + STR + r',name:' + STR + r',city:' + STR + r',address:' + STR + r',phone:' + STR + r',',
    re.M)


def load_clinics():
    text = SRC.read_text(encoding='utf-8')
    out = []
    for m in ROW.finditer(text):
        cid, name, city, address, phone = (json.loads(g) for g in m.groups())
        out.append({'id': cid, 'name': name.strip(), 'city': city.strip(),
                    'address': address.strip(), 'phone': phone.strip()})
    if not out:
        sys.exit('Nije pronađena nijedna ordinacija u ' + str(SRC))
    return out


def clinic_slug(c, city_slug):
    """id je 'imp-<naziv>-<grad>[-N]' -> '<naziv>[-N]' (jedinstven unutar grada)."""
    s = c['id']
    if s.startswith('imp-'):
        s = s[4:]
    m = re.match(r'^(.*)-' + re.escape(city_slug) + r'(-\d+)?$', s)
    if m:
        s = m.group(1) + (m.group(2) or '')
    return s


# ---------------------------------------------------------------------------
def url(path):
    return BASE_URL.rstrip('/') + path


def clip(text, n=158):
    text = re.sub(r'\s+', ' ', text).strip()
    return text if len(text) <= n else text[:n - 1].rstrip(' ,.;') + '…'


def page(title, description, canonical_path, body, jsonld=None):
    canonical = url(canonical_path)
    ld = ''
    if jsonld:
        ld = '\n<script type="application/ld+json">' + json.dumps(jsonld, ensure_ascii=False).replace('</', '<\\/') + '</script>'
    return f'''<!DOCTYPE html>
{MARKER}
<html lang="sr">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{esc(title)}</title>
<meta name="description" content="{esc(description)}">
<link rel="canonical" href="{esc(canonical)}">
<meta name="robots" content="index, follow">
<meta property="og:type" content="website">
<meta property="og:site_name" content="{SITE_NAME}">
<meta property="og:title" content="{esc(title)}">
<meta property="og:description" content="{esc(description)}">
<meta property="og:url" content="{esc(canonical)}">
<link rel="icon" href="/img/logo.webp">
<link rel="stylesheet" href="/css/style.css">{ld}
</head>
<body>
<header class="site-header">
  <div class="container nav-inner">
    <a href="/index.html" class="logo" aria-label="{SITE_NAME}"><img src="/img/logo.webp" alt="" class="logo-mark"> {SITE_NAME}</a>
    <nav class="main-nav">
      <a href="/index.html">Početna</a>
      <a href="/pretraga.html">Pronađi ordinaciju</a>
      <a href="/kontakt.html">Kontakt</a>
    </nav>
  </div>
</header>
<main class="section-tight">
<div class="container">
{body}
</div>
</main>
<footer class="site-footer">
  <div class="container">
    <div class="footer-bottom"><span>&copy; {SITE_NAME}. Podaci o ordinacijama su iz javno dostupne evidencije.</span></div>
  </div>
</footer>
</body>
</html>
'''


def report_href(c):
    return ('/kontakt.html?subject=netacan-podatak&clinic=' + quote(c['name']) +
            '&city=' + quote(c['city']) + '&id=' + quote(c['id']))


def clinic_page(c, city_slug, slug):
    path = f'/{city_slug}/{slug}/'
    title = f"{c['name']} – {c['city']} | {SITE_NAME}"
    desc = f"{c['name']}, {c['address']}."
    if c['phone']:
        desc += f" Telefon: {c['phone']}."
    desc += f" Adresa i kontakt ordinacije, grad: {c['city']}."
    phone_html = (f'<p><strong>Telefon:</strong> <a href="tel:{esc(re.sub(r"[^+0-9]", "", c["phone"]))}">{esc(c["phone"])}</a></p>'
                  if c['phone'] else '<p><strong>Telefon:</strong> nije dostupan</p>')
    body = f'''<div class="breadcrumbs"><a href="/index.html">Početna</a> / <a href="/{city_slug}/">{esc(c['city'])}</a> / {esc(c['name'])}</div>
<article class="info-card">
  <h1>{esc(c['name'])}</h1>
  <p><strong>Adresa:</strong> {esc(c['address'])}</p>
  {phone_html}
  <p><strong>Grad:</strong> <a href="/{city_slug}/">{esc(c['city'])}</a></p>
  <p>Radno vreme, usluge i ocene za ovu ordinaciju još nisu dostupni.</p>
  <p>
    <a class="btn btn-primary" href="/ordinacija.html?id={esc(c['id'])}">Otvori u pretrazi</a>
  </p>
  <p style="font-size:14px;"><a href="{esc(report_href(c))}">Prijavi netačan podatak</a></p>
</article>'''
    ld = {"@context": "https://schema.org", "@type": "Dentist", "name": c['name'],
          "url": url(path), "address": c['address']}
    if c['phone']:
        ld["telephone"] = c['phone']
    return path, page(title, clip(desc), path, body, ld)


def city_page(city, slug, clinics_with_slug):
    path = f'/{slug}/'
    n = len(clinics_with_slug)
    title = f"Stomatološke ordinacije – {city} ({n}) | {SITE_NAME}"
    desc = clip(f"Stomatološke ordinacije, grad: {city}. Spisak ordinacija ({n}) sa adresama i telefonima. "
                f"Pronađite zubara preko {SITE_NAME}.")
    items = '\n'.join(
        f'  <li><a href="/{slug}/{cs}/">{esc(c["name"])}</a> <span style="color:var(--muted);">— {esc(c["address"])}</span></li>'
        for c, cs in sorted(clinics_with_slug, key=lambda x: x[0]['name'].lower()))
    body = f'''<div class="breadcrumbs"><a href="/index.html">Početna</a> / {esc(city)}</div>
<h1>Stomatološke ordinacije – {esc(city)}</h1>
<p>Grad: {esc(city)}. Pregled stomatoloških ordinacija ({n}). Za pretragu po usluzi i filtere
<a href="/pretraga.html?city={esc(quote(city))}">otvorite pretragu</a>.</p>
<ul class="clinic-link-list">
{items}
</ul>'''
    return path, page(title, desc, path, body)


def sitemap(paths):
    urls = '\n'.join(f'  <url><loc>{html.escape(url(p))}</loc></url>' for p in paths)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + '\n</urlset>\n')


def robots():
    # Namerno bez Disallow za prijava/nalog/dodaj-ordinaciju: te stranice nose noindex
    # i preusmerenje, a robots.txt zabrana bi sprečila crawler da vidi noindex.
    return f"User-agent: *\nAllow: /\n\nSitemap: {url('/sitemap.xml')}\n"


def write(base, rel_path, content):
    target = base / rel_path.strip('/') / 'index.html'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding='utf-8')


def clean_previous(base):
    """Briše samo ranije generisane direktorijume (prepoznaju se po MARKER-u)."""
    removed = 0
    for d in base.iterdir():
        idx = d / 'index.html'
        if d.is_dir() and idx.exists() and d.name not in RESERVED and not d.name.startswith('.'):
            if MARKER in idx.read_text(encoding='utf-8', errors='ignore')[:200]:
                shutil.rmtree(d)
                removed += 1
    return removed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sample', metavar='DIR', help='generiši samo jedan grad i jednu ordinaciju u DIR')
    args = ap.parse_args()

    clinics = load_clinics()
    by_city = defaultdict(list)
    skipped = 0
    for c in clinics:
        if c['city'] in SKIP_CITIES:
            skipped += 1
            continue
        by_city[c['city']].append(c)

    # slugovi gradova + provere sudara
    city_slugs = {}
    for city in by_city:
        s = slugify(city)
        if not s or s in RESERVED:
            sys.exit(f'Slug grada "{city}" -> "{s}" je prazan ili rezervisan')
        if s in city_slugs.values():
            sys.exit(f'Dva grada daju isti slug: {s}')
        city_slugs[city] = s

    plan = {}  # grad -> [(clinic, slug)]
    for city, lst in by_city.items():
        seen = set()
        plan[city] = []
        for c in lst:
            cs = clinic_slug(c, city_slugs[city])
            if not cs or cs in seen:
                sys.exit(f'Sudar slugova ordinacija u {city}: {cs} ({c["id"]})')
            seen.add(cs)
            plan[city].append((c, cs))

    if args.sample:
        out = Path(args.sample)
        out.mkdir(parents=True, exist_ok=True)
        city = 'Niš' if 'Niš' in plan else next(iter(plan))
        pth, html_ = city_page(city, city_slugs[city], plan[city])
        write(out, pth, html_)
        c, cs = plan[city][0]
        pth, html_ = clinic_page(c, city_slugs[city], cs)
        write(out, pth, html_)
        print('Uzorak upisan u', out)
        return

    removed = clean_previous(ROOT)
    paths = ['/', '/pretraga.html', '/kontakt.html']
    n_clinic = 0
    for city in sorted(plan, key=lambda x: city_slugs[x]):
        slug = city_slugs[city]
        pth, html_ = city_page(city, slug, plan[city])
        write(ROOT, pth, html_)
        paths.append(pth)
        for c, cs in plan[city]:
            pth, html_ = clinic_page(c, slug, cs)
            write(ROOT, pth, html_)
            paths.append(pth)
            n_clinic += 1
    (ROOT / 'sitemap.xml').write_text(sitemap(paths), encoding='utf-8')
    (ROOT / 'robots.txt').write_text(robots(), encoding='utf-8')
    print(f'Gradova: {len(plan)}, ordinacija: {n_clinic}, preskočeno (nepoznat grad): {skipped}, '
          f'obrisano starih direktorijuma: {removed}, URL-ova u sitemap-u: {len(paths)}')


if __name__ == '__main__':
    main()
