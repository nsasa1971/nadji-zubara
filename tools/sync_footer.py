#!/usr/bin/env python3
"""Podnožje ručno pisanih stranica = podnožje iz index.html (jedan izvor).
Pokretanje: python3 tools/sync_footer.py. Generisane stranice već dobijaju isto podnožje iz build_pages.py.
Stranice bez <footer class="site-footer"> se ne diraju; generisane (sa oznakom) se preskaču.
Ako stranica ima rečenicu o OpenStreetMap atribuciji (pretraga.html, zbog mape), ona se zadržava."""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FOOT = re.compile(r'<footer class="site-footer">.*?</footer>', re.S)
OSM = ' Koordinate: © <a href="https://www.openstreetmap.org/copyright" target="_blank" rel="noopener">OpenStreetMap contributors</a>.'


def main():
    src = FOOT.search((ROOT / 'index.html').read_text(encoding='utf-8')).group(0)
    changed = []
    for p in sorted(ROOT.glob('*.html')):
        if p.name == 'index.html':
            continue
        s = p.read_text(encoding='utf-8')
        if 'generated by tools/build_pages.py' in s or not FOOT.search(s):
            continue
        new = src
        if OSM in FOOT.search(s).group(0):
            new = new.replace('Sva prava zadržana.</span>', 'Sva prava zadržana.' + OSM + '</span>', 1)
        out = FOOT.sub(lambda m: new, s, count=1)
        if out != s:
            p.write_text(out, encoding='utf-8')
            changed.append(p.name)
    print('podnožje usklađeno:', ', '.join(changed) or 'ništa')


if __name__ == '__main__':
    sys.exit(main())
